#!/usr/bin/env bash
# Tinta Office Flatpak: the bundle manifest under this build's app id, and the single-file bundle.
#
#   packaging/linux/tinta-flatpak.sh generate            write flatpak/<brand id>.bundle.yml
#   packaging/linux/tinta-flatpak.sh check               fail if that file is out of date
#   packaging/linux/tinta-flatpak.sh bundle [--no-test] [--oci] [TARBALL]
#                                                        $DIST/<slug>-<version>-linux-<arch>.flatpak
#
# The release's own bundle manifest (flatpak/ai.storyteller.<app>.bundle.yml) installs files named
# after the release's app id, but this build's Linux tarball carries the Tinta id (tinta-brand.sh
# renames the desktop entry, AppStream metadata, MIME file and icons), so that manifest cannot
# package it. `generate` derives the Tinta manifest from the release's one with the same rewrite
# tinta-brand.sh applies to the desktop files, so upstream changes (runtime, permissions, the CUPS
# module) arrive with each sync: run `generate` after a sync and commit the result. It also drops
# the read-only grant on ~/.local/share/ArtCraft/versions, which only the ArtCraft launcher writes.
#
# `bundle` repackages $DIST/<slug>-<version>-linux-<arch>.tar.gz from package.sh (or TARBALL),
# like flatpak-bundle.sh does for the release. It needs flatpak, flatpak-builder and the network
# (the freedesktop runtime and SDK come from Flathub); unless --no-test it installs the bundle
# per-user and runs the CLI inside the sandbox as a smoke test.
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# The release's binary name and product name; everything else follows from them.
APP_BIN=pdfcraft
UPSTREAM_NAME=PdfCraft
# Build commands for files only this fork's tarball carries, appended to the app module's build
# commands (after its documentation line). One command per line; empty when there are none.
TINTA_INSTALL=''

for env_file in "$HERE/../env.sh" "$HERE/../common.sh"; do
  if [[ -f "$env_file" ]]; then
    # shellcheck source=/dev/null
    . "$env_file"
    break
  fi
done
[[ -n "${ROOT:-}" ]] || { echo "error: no packaging/env.sh or packaging/common.sh" >&2; exit 1; }
BRAND_PREFIX="$(printf '%s' "$APP_BIN" | tr '[:lower:]' '[:upper:]')"
UPSTREAM_ID="ai.storyteller.$APP_BIN"
UPSTREAM_REPO="storytold/$APP_BIN"
# shellcheck source=tinta-brand.sh
. "$HERE/tinta-brand.sh"

UPSTREAM_MANIFEST="$HERE/flatpak/$UPSTREAM_ID.bundle.yml"
MANIFEST="$HERE/flatpak/$BRAND_ID.bundle.yml"
FLATHUB=https://dl.flathub.org/repo/flathub.flatpakrepo
ARTCRAFT_GRANT='--filesystem=xdg-data/ArtCraft/versions:ro'

# The Tinta manifest, on stdout.
render() {
  [[ -f "$UPSTREAM_MANIFEST" ]] || { echo "error: $UPSTREAM_MANIFEST not found" >&2; exit 1; }
  local tmp
  tmp="$(mktemp)"
  {
    echo "# GENERATED by packaging/linux/tinta-flatpak.sh from the release's bundle manifest."
    echo "# Do not edit: change the release's manifest or the script, then run"
    echo "# \`packaging/linux/tinta-flatpak.sh generate\`. Build the bundle with"
    echo "# \`packaging/linux/tinta-flatpak.sh bundle\`."
    echo "#"
    # The release's from-source manifest has no Tinta counterpart (yet), so the comment pointing
    # at it goes too.
    grep -v -F -e "$ARTCRAFT_GRANT" "$UPSTREAM_MANIFEST" |
      sed -e '/(same directory) is the from-source manifest/,/packaging-lint/c\
# A from-source manifest under the Tinta id (for Flathub) does not exist yet.'
  } >"$tmp"
  brand_rewrite "$tmp"
  if [[ -n "$TINTA_INSTALL" ]]; then
    local anchor="cp -R share/doc/$APP_BIN /app/share/doc/" extra
    grep -q -F -e "$anchor" "$tmp" || {
      rm -f "$tmp"
      echo "error: no '$anchor' build command in $UPSTREAM_MANIFEST to add this fork's files after" >&2
      exit 1
    }
    extra="$(mktemp)"
    printf '%s\n' "$TINTA_INSTALL" | sed -e 's/^/      - /' >"$extra"
    sed -i -e "\|$anchor|r $extra" "$tmp"
    rm -f "$extra"
  fi
  # The release's bundle script is not the one that builds this manifest.
  sed -i -e "s|packaging/linux/flatpak-bundle.sh|packaging/linux/tinta-flatpak.sh bundle|g" \
    -e "s|$APP_BIN-<version>-linux-<arch>|$BRAND_SLUG-<version>-linux-<arch>|g" "$tmp"
  if grep -n -i -e 'storyteller' -e 'artcraft' -e 'storytold' -e 'Learning Machines' "$tmp" >&2; then
    rm -f "$tmp"
    echo "error: the Tinta manifest still names the release's identity (above)" >&2
    exit 1
  fi
  if ! grep -q "^id: $BRAND_ID\$" "$tmp"; then
    rm -f "$tmp"
    echo "error: the Tinta manifest's id is not $BRAND_ID" >&2
    exit 1
  fi
  cat "$tmp"
  rm -f "$tmp"
  return
}

check() {
  local want
  want="$(mktemp)"
  render >"$want"
  if ! diff -u "$MANIFEST" "$want"; then
    rm -f "$want"
    echo "error: $MANIFEST is out of date; run packaging/linux/tinta-flatpak.sh generate" >&2
    exit 1
  fi
  rm -f "$want"
  echo "$MANIFEST is up to date"
  return
}

bundle() {
  local test=1 oci=0 tarball="" arch basename work out
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --no-test) test=0; shift ;;
      --oci) oci=1; shift ;;
      -*) echo "unknown argument: $1" >&2; exit 2 ;;
      *) tarball="$1"; shift ;;
    esac
  done
  check >/dev/null
  arch="$(uname -m)"
  case "$arch" in
    x86_64) ;;
    aarch64 | arm64) arch=aarch64 ;;
    *) echo "unsupported architecture $arch" >&2; exit 2 ;;
  esac
  basename="$BRAND_SLUG-$VERSION-linux-$arch"
  tarball="${tarball:-$DIST/$basename.tar.gz}"
  [[ -f "$tarball" ]] || { echo "error: $tarball not found (run packaging/linux/package.sh --formats tar first)" >&2; exit 1; }
  for tool in flatpak flatpak-builder; do
    command -v "$tool" >/dev/null || { echo "error: $tool not found (apt install flatpak flatpak-builder librsvg2-common)" >&2; exit 1; }
  done
  echo "==> $BRAND_NAME $VERSION Flatpak bundle for $arch from $(basename "$tarball")"

  work="$CARGO_TARGET_DIR/tinta-flatpak"
  rm -rf "$work"
  mkdir -p "$work/stage"
  tar -xzf "$tarball" -C "$work/stage" --strip-components=1
  [[ -x "$work/stage/bin/$APP_BIN" ]] || { echo "error: $tarball has no bin/$APP_BIN" >&2; exit 1; }
  [[ -f "$work/stage/share/applications/$BRAND_ID.desktop" ]] || {
    echo "error: $tarball has no share/applications/$BRAND_ID.desktop (not a Tinta build?)" >&2
    exit 1
  }
  cp "$MANIFEST" "$work/$BRAND_ID.yml"

  flatpak remote-add --user --if-not-exists flathub "$FLATHUB"
  # --disable-rofiles-fuse: no FUSE in containers and CI runners.
  flatpak-builder --user --install-deps-from=flathub --disable-rofiles-fuse --force-clean \
    --default-branch=stable --repo="$work/repo" --state-dir="$work/state" "$work/build" "$work/$BRAND_ID.yml"

  out="$DIST/$basename.flatpak"
  # --runtime-repo lets `flatpak install` fetch the freedesktop runtime from Flathub if missing.
  flatpak build-bundle --runtime-repo="$FLATHUB" "$work/repo" "$out" "$BRAND_ID" stable
  echo "wrote $out"
  if [[ "$oci" = 1 ]]; then
    rm -rf "$DIST/$basename-oci"
    flatpak build-bundle --oci "$work/repo" "$DIST/$basename-oci" "$BRAND_ID" stable
    echo "wrote OCI layout to $DIST/$basename-oci"
  fi

  if [[ "$test" = 1 ]]; then
    flatpak install --user -y --noninteractive --reinstall "$out"
    flatpak info --user "$BRAND_ID"
    flatpak run --command="$APP_BIN-cli" "$BRAND_ID" --version
    flatpak run --command=sh "$BRAND_ID" -c "grep -x 'StartupWMClass=$BRAND_ID' /app/share/applications/$BRAND_ID.desktop && ls /app/share/metainfo/$BRAND_ID.metainfo.xml /app/share/icons/hicolor/*/apps/$BRAND_ID.*"
  fi
  echo "==> done"
  ls -lh "$out"
  return
}

case "${1:-}" in
  generate)
    render >"$MANIFEST.tmp"
    mv -f "$MANIFEST.tmp" "$MANIFEST"
    echo "wrote $MANIFEST"
    ;;
  check) check ;;
  bundle) shift; bundle "$@" ;;
  -h | --help | "") sed -n '2,20p' "$0" ;;
  *) echo "unknown command: $1 (generate, check or bundle)" >&2; exit 2 ;;
esac
